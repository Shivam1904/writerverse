# Read DATABASE_URL via decouple so every entrypoint agrees (runserver, manage.py,
# shell, tests, gunicorn). dj_database_url.config() reads os.environ directly and
# never sees backend/.env, which silently dropped the dev server onto SQLite
# while migrate/seed used Postgres — split-brain. See P0-1.
# conn_max_age — how long Django keeps each DB connection open between requests.
# A high value pins ONE Postgres connection per worker-thread for that whole
# window; combined with the shell's bursty per-page parallel queries and the
# long-lived staleness SSE, that exhausts Postgres ("FATAL: too many clients").
# 0 = open/close per request → no pile-up, and the correct setting behind a
# transaction-mode pooler (e.g. Neon's pooler endpoint, which prod uses). Only
# raise it on a DIRECT, un-pooled connection where you want reuse to cut connect
# latency and have the connection budget to spare. Override via CONN_MAX_AGE env.
CONN_MAX_AGE = config("CONN_MAX_AGE", default=0, cast=int)
DATABASES = {
    "default": dj_database_url.parse(
        config(
            "DATABASE_URL",
            default=f"sqlite:///{BASE_DIR / 'db' / 'sqlite' / 'db.sqlite3'}",
        ),
        conn_max_age=CONN_MAX_AGE,
        conn_health_checks=True,
        ssl_require=not DEBUG,  # Require SSL in production (Neon requirement)
    )
}

