# LangSmith / LangChain tracing — SDKs read os.environ, not python-decouple.
# Sync .env → environ so tracing works for runserver, tests, and shells without
# manual export. Pre-set shell env (e.g. make local) wins over .env.
# LANGSMITH_HIDE_INPUTS / _OUTPUTS=true make the SDK drop prompts / replies
# (the author's text) from every trace; unset = full traces.
for _langsmith_key in (
    'LANGSMITH_TRACING',
    'LANGSMITH_API_KEY',
    'LANGSMITH_PROJECT',
    'LANGSMITH_ENDPOINT',
    'LANGSMITH_HIDE_INPUTS',
    'LANGSMITH_HIDE_OUTPUTS',
):
    _langsmith_val = config(_langsmith_key, default='')
    if _langsmith_val and not os.environ.get(_langsmith_key):
        os.environ[_langsmith_key] = str(_langsmith_val)
# Tests never upload traces, even when a dev's .env or shell turns tracing on
# (they spent the LangSmith quota and printed 429 warnings).
if RUNNING_TESTS:
    os.environ['LANGSMITH_TRACING'] = 'false'
    os.environ['LANGCHAIN_TRACING_V2'] = 'false'
# Local log of every AI call's full prompt and reply (ai_engine/call_log.py):
# AI_CALL_LOG=1 in backend/.env. Never on a deployed server (author text), nor
# in tests (fake calls would fill the dev's log).
AI_CALL_LOG = (config('AI_CALL_LOG', default=False, cast=bool)
               and not IS_DEPLOYED and not RUNNING_TESTS)
# No project set → pick one per environment, so prod traces never land in dev.
if not os.environ.get('LANGSMITH_PROJECT'):
    _is_prod = SECURE_PROD or RUNTIME == PRODUCTION
    os.environ['LANGSMITH_PROJECT'] = 'writerverse-prod' if _is_prod else 'writerverse-dev'


